/**
 * Migration CLI. Runs under Bun directly (no MikroORM CLI / ts-node involved).
 *
 *   bun run migration:up
 *   bun run migration:down [--all]
 *   bun run migration:create <name>
 *
 * up/down connect with MIGRATION_DATABASE_URL (schema owner role).
 */
import { readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { migrateDown, migrateUp } from '../src/infrastructure/persistence/migrator';

const MIGRATIONS_DIR = join(import.meta.dir, '../src/infrastructure/persistence/migrations');

function requireMigrationUrl(): string {
  const url = process.env.MIGRATION_DATABASE_URL;
  if (!url) {
    throw new Error('MIGRATION_DATABASE_URL is not set (see .env.example).');
  }
  return url;
}

function timestamp(now: Date): string {
  const pad = (value: number) => String(value).padStart(2, '0');
  return (
    `${now.getUTCFullYear()}${pad(now.getUTCMonth() + 1)}${pad(now.getUTCDate())}` +
    `${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}${pad(now.getUTCSeconds())}`
  );
}

async function regenerateIndex(): Promise<void> {
  const files = (await readdir(MIGRATIONS_DIR))
    .filter((file) => /^Migration\d{14}_[a-z0-9_]+\.ts$/.test(file))
    .sort();
  const names = files.map((file) => file.replace(/\.ts$/, ''));
  const content = [
    '// Generated by `bun run migration:create`. Order matters: migrations run top to bottom.',
    ...names.map((name) => `import { ${name} } from './${name}';`),
    '',
    'export const migrationsList = [',
    ...names.map((name) => `  { name: '${name}', class: ${name} },`),
    '];',
    '',
  ].join('\n');
  await Bun.write(join(MIGRATIONS_DIR, 'index.ts'), content);
}

async function create(rawName: string | undefined): Promise<void> {
  const name = rawName
    ?.trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
  if (!name) {
    throw new Error('Usage: bun run migration:create <name>');
  }
  const className = `Migration${timestamp(new Date())}_${name}`;
  const template = `import { Migration } from '@mikro-orm/migrations';

export class ${className} extends Migration {
  override name = '${className}';

  override up(): void {
    this.addSql('');
  }

  override down(): void {
    this.addSql('');
  }
}
`;
  await Bun.write(join(MIGRATIONS_DIR, `${className}.ts`), template);
  await regenerateIndex();
  console.log(`Created ${className}.ts — write both up() and down().`);
}

const [command, arg] = process.argv.slice(2);

switch (command) {
  case 'up': {
    const result = await migrateUp(requireMigrationUrl());
    console.log(result.applied.length ? `Applied: ${result.applied.join(', ')}` : 'Up to date.');
    break;
  }
  case 'down': {
    const result = await migrateDown(requireMigrationUrl(), { all: arg === '--all' });
    console.log(
      result.applied.length ? `Reverted: ${result.applied.join(', ')}` : 'Nothing to revert.',
    );
    break;
  }
  case 'create':
    await create(arg);
    break;
  default:
    console.error('Usage: bun scripts/migrate.ts <up|down [--all]|create <name>>');
    process.exit(1);
}
